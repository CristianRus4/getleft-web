// Printables: page data and English text for the printable tools.
//
//   scripts/printables/<id>.mjs        one printable page: slug, titles, copy, FAQ
//   tools/print/<id>.js                its drawing: LeftPrint.define({ id, fields, render })
//   i18n/tools-runtime/print/<ns>.json  English text the drawings and controls use,
//                                      one file per namespace (ui, sheet, <id>)
//
// scripts/build-tools-seo.mjs builds tools/<slug>.html for each printable and
// tools/printables.html (the hub), and calls writePrintStrings(), which merges
// the text files into i18n/tools-runtime/en.json under "print" (translated with
// the other tool runtime strings) and writes tools/print/strings.js, the
// English fallback the browser loads.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export async function loadPrintables(root) {
  const dir = path.join(root, 'scripts/printables');
  const files = (await fs.readdir(dir).catch(() => [])).filter(f => f.endsWith('.mjs')).sort();
  const list = [];
  for (const f of files) {
    const mod = await import(pathToFileURL(path.join(dir, f)).href);
    const p = mod.default;
    if (!p || !p.id || !p.slug) throw new Error(`printables: ${f} must export default { id, slug, ... }`);
    if (!/^printable-[a-z0-9-]+$/.test(p.slug)) throw new Error(`printables: ${f} slug must start with "printable-"`);
    const js = path.join(root, 'tools/print', `${p.id}.js`);
    if (!(await fs.access(js).then(() => true, () => false))) throw new Error(`printables: missing tools/print/${p.id}.js for ${f}`);
    list.push(p);
  }
  return list.sort((a, b) => (a.order ?? 99) - (b.order ?? 99) || a.slug.localeCompare(b.slug));
}

export async function writePrintStrings(root) {
  const dir = path.join(root, 'i18n/tools-runtime/print');
  const files = (await fs.readdir(dir).catch(() => [])).filter(f => f.endsWith('.json')).sort();
  const print = {};
  for (const f of files) print[f.replace(/\.json$/, '')] = JSON.parse(await fs.readFile(path.join(dir, f), 'utf8'));

  const enFile = path.join(root, 'i18n/tools-runtime/en.json');
  const en = JSON.parse(await fs.readFile(enFile, 'utf8'));
  en.print = print;
  const enText = JSON.stringify(en, null, 2) + '\n';
  if ((await fs.readFile(enFile, 'utf8')) !== enText) await fs.writeFile(enFile, enText);

  const js = `// Generated by scripts/build-tools-seo.mjs from i18n/tools-runtime/print/*.json. Do not edit.\n`
    + `window.LEFT_PRINT_EN = ${JSON.stringify(print, null, 1)};\n`;
  const jsFile = path.join(root, 'tools/print/strings.js');
  const old = await fs.readFile(jsFile, 'utf8').catch(() => '');
  if (old !== js) await fs.writeFile(jsFile, js);
  return print;
}
